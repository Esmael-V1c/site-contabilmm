import { existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { isIP } from "node:net";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GENERATED_START = "<!-- CONTABIL-MM:SEO:START -->";
const GENERATED_END = "<!-- CONTABIL-MM:SEO:END -->";
const SITEMAP_MARKER = "<!-- Generated by scripts/build-seo.mjs -->";
const PAGE_DEFINITIONS = [
  { file: "index.html", label: "Início" },
  { file: "servicos.html", label: "Serviços" },
  { file: "sobre.html", label: "Sobre nós" },
  { file: "contato.html", label: "Contato" },
  { file: "privacidade.html", label: "Privacidade", optional: true },
];

function escapeMarkup(value) {
  return value.replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character]);
}

function serializeSchema(value) {
  // Keep configured strings from closing a script element in the HTML parser.
  return JSON.stringify(value, null, 2)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/&/g, "\\u0026")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

function textField(value, field) {
  if (typeof value !== "string" || !value.trim() || value.length > 4000) {
    throw new Error(`O campo ${field} deve conter um texto válido.`);
  }
  return value.trim();
}

export function normalizeSiteUrl(value) {
  if (value === "") return "";
  if (typeof value !== "string" || value !== value.trim()) {
    throw new Error("siteUrl deve ser vazio ou conter a origem HTTPS definitiva do site.");
  }
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error("siteUrl inválido. Informe a origem HTTPS definitiva, sem caminho ou parâmetros.");
  }
  const hostname = url.hostname.toLowerCase();
  const isReserved = /(^|\.)(localhost|local|internal|test|invalid|example)$/.test(hostname);
  const isPreview = /(^|\.)(vercel\.app|netlify\.app|pages\.dev|github\.io)$/.test(hostname);
  if (url.protocol !== "https:" || url.username || url.password || url.port ||
      url.pathname !== "/" || url.search || url.hash || isIP(hostname.replace(/^\[|\]$/g, "")) ||
      !hostname.includes(".") || isReserved || isPreview ||
      !/^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$/.test(hostname)) {
    throw new Error("siteUrl deve ser um domínio HTTPS definitivo, sem IP, endereço local, domínio de preview, caminho ou parâmetros.");
  }
  return url.origin;
}

function validateConfig(config) {
  if (!config || typeof config !== "object" || Array.isArray(config)) {
    throw new Error("seo.config.json precisa conter um objeto de configuração.");
  }
  const origin = normalizeSiteUrl(config.siteUrl);
  const siteName = textField(config.siteName, "siteName");
  const token = config.searchConsoleVerification;
  if (typeof token !== "string" || (token !== "" && !/^[A-Za-z0-9_-]{1,256}$/.test(token))) {
    throw new Error("searchConsoleVerification deve ser vazio ou conter apenas o token de verificação do Google.");
  }
  if (!config.pages || typeof config.pages !== "object" || Array.isArray(config.pages)) {
    throw new Error("O campo pages deve conter os títulos e descrições das páginas.");
  }
  return { origin, siteName, token, pages: config.pages };
}

function pageUrl(origin, file) {
  return `${origin}/${file === "index.html" ? "" : file}`;
}

